          opacity: 1,
        }),
        gsap.fromTo(
          "#loading-section .slogan span",
          {
            opacity: 0,
            scale: 1.5,
            translateY: "100%",
          },
          {
            opacity: 1,
            scale: 1,
            translateY: 0,
            delay: 1.2,
            duration: 1,
            ease: "power3",
            stagger: 1 / 3,
            onStart: () => {
              sloganVisible.set(true);
            },
            onComplete: () => {
              gsap.fromTo(
                "#loading-section .map",
                {
                  opacity: 0,
                },
                {
                  opacity: 1,
                  ease: "power3.out",
                  duration: 1.5,
                  onStart: () => {
                    mapVisible.set(true);
                  },
                }
              );
            },
          }
        ),
      ])
      .add([
        gsap.to(
          "#loading-section .heading, #loading-section .slogan, #loading-section .logo",
          {
            // filter: 'blur(10px)',
            // scale: 2,
            ease: "power2.inOut",
            opacity: 0,
            duration: 0.5,
            onStart: loadingComplete,
            delay: 5,
          }
        ),
        gsap.to("#loading-section .map", {
          transformOrigin: "center",
          ease: "power2.inOut",
          duration: 1,
          opacity: 0,
          scale: 2,
          delay: 5,
        }),
      ]);
  };

  onMount(async () => {
    storageIntroIsSeen.subscribe((value) => {
      introIsSeen = value;
    });
    if (!showOnPage || introIsSeen) {
      loadingComplete();
    } else {
      animateMap();
    }
  });

  const title = "БЛАГОДЕЙСТВИЕ";
</script>

