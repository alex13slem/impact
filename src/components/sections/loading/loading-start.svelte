  const animateMap = async () => {
    gsap
      .timeline({
        onStart: loadingStart,
      })
      .add([
        gsap.set("#loading-section .map", {
          opacity: 0,
        }),
        gsap.set("#loading-section .heading .letter", {
          opacity: 0,
        }),
        gsap.set("#loading-section .slogan", {
          opacity: 0,
        }),
      ])
      .delay(1)
      .add([
        gsap.to("#loading-section g.inner, #loading-section g.outer", {
          scale: 0,

          opacity: 0,
          duration: 1.5,
          ease: "back.out",
          transformOrigin: "center center",
          filter: "blur(10px)",
        }),
        gsap.to("#loading-section .heading .letter", {
          opacity: 1,
          stagger: 0.1,
          delay: 0.5,
